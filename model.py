"""Сеть из ролика 3Blue1Brown: 784 входа, два скрытых слоя по 16, 10 выходов.

Картинка цифры — это 28×28 чисел яркости. Их вытягивают в один столбец из 784
чисел и подают на первый слой. Каждый следующий слой берёт все числа предыдущего,
умножает на свои веса, прибавляет смещения и (кроме последнего слоя) прогоняет
через сигмоиду. На выходе десять сырых оценок, по одной на цифру 0–9.
"""

from pathlib import Path

import torch
from torch import nn

# Корень проекта — папка этого файла, а не та, откуда вызвали python.
# Иначе запуск из другой директории положил бы MNIST и снимки весов мимо проекта.
ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"
OUTPUT_DIR = ROOT / "output"
CHECKPOINT_PATH = OUTPUT_DIR / "checkpoint.pt"
# Отдельный кадр на каждый сохранённый шаг. Каталог внутри output/, в git не входит.
HISTORY_DIR = OUTPUT_DIR / "history"

# Один и тот же seed в обучении и на странице весов.
# До первого снимка страница показывает ровно те веса, с которых train.py начнёт.
SEED = 0

# Настройки цикла. Скорость 0.1 — осторожный старт для сигмоиды
# и перекрёстной энтропии. Её не подбирали по проверочным 10 000.
EPOCHS = 10
BATCH_SIZE = 64
LEARNING_RATE = 0.1
# Каждые столько вызовов optimizer.step() пишется отдельный кадр истории.
# Конец эпохи пишется ещё раз, даже если номер шага на 10 не делится.
HISTORY_EVERY_STEPS = 10


class DigitNet(nn.Module):
    """Полносвязная сеть 784 → 16 → 16 → 10.

    Веса и смещения создаёт сам nn.Linear: небольшие случайные числа.
    Широкий нормальный разброс, как в первой главе Нильсена, сюда не копируем.
    На сигмоиде такие веса запирают нейрон около 0 или 1, и градиент почти
    не проходит, то есть сеть почти не учится.
    """

    def __init__(self):
        super().__init__()
        # weight имеет форму (сколько нейронов в этом слое, сколько входов).
        # hidden1.weight — (16, 784): строка i есть 784 веса i-го нейрона.
        # Эти 784 числа укладываются обратно в картинку 28×28.
        self.hidden1 = nn.Linear(784, 16)
        # hidden2.weight — (16, 16): как второй скрытый слой смотрит на первый.
        self.hidden2 = nn.Linear(16, 16)
        # output.weight — (10, 16): строка d толкает оценку цифры d.
        # Сигмоиды здесь нет. CrossEntropyLoss ждёт сырые оценки (логиты)
        # и сам применяет log-softmax. Сигмоида на выходе сломала бы эту ошибку.
        self.output = nn.Linear(16, 10)

    def forward(self, images):
        """images: батч формы (N, 1, 28, 28), яркость от 0 до 1.

        Возвращает (N, 10) — десять оценок на каждую картинку.
        Номер самой большой оценки и есть предсказанная цифра.
        Для argmax вероятности не нужны: порядок оценок тот же, что у softmax.
        """
        # Вытянуть каждую картинку в строку из 784 чисел.
        # Порядок: слева направо, сверху вниз, тот же, что у пикселей.
        flat = images.view(images.shape[0], -1)
        # Сигмоида сжимает любую сумму в диапазон (0, 1). Так в ролике.
        hidden = torch.sigmoid(self.hidden1(flat))
        hidden = torch.sigmoid(self.hidden2(hidden))
        return self.output(hidden)
